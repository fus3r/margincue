// Regenerates hooks/assets.ts from the prompts and profiles, so the
// mod folder is self-contained. Run from anywhere:
//   node mods/claude-code/scripts/sync-assets.ts [--check]
// --check exits 1 when assets.ts is out of date instead of writing it.
import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const mod = resolve(here, '..')
const repo = resolve(mod, '..', '..')
const system = readFileSync(join(repo, 'prompts', 'system.md'), 'utf8')
const profiles: Record<string, string> = {}
for (const name of readdirSync(join(repo, 'profiles')).sort()) {
  if (!name.endsWith('.md')) continue
  profiles[name.slice(0, -3)] = readFileSync(join(repo, 'profiles', name), 'utf8')
}

const systemDesign = join(repo, 'profiles', 'system-design', 'profile.md')
profiles['system-design'] = readFileSync(systemDesign, 'utf8')
const bundles = ['general', 'ml-research', 'system-design'].map((profile) =>
  JSON.parse(readFileSync(join(repo, 'profiles', profile, 'bundle.json'), 'utf8')))
const expertSystem = readFileSync(join(repo, 'prompts', 'system.v2.md'), 'utf8')
const sheetSystem = readFileSync(join(repo, 'bench', 'sheet', 'product', 'sheet-prompt.md'), 'utf8').trim()

const body = [
  '// Generated by scripts/sync-assets.ts from prompts and compiled profile bundles.',
  '// Do not edit: change the sources and run `node mods/claude-code/scripts/sync-assets.ts`.',
  "import type { Assets } from '../core/types'",
  '',
  `export const ASSETS: Assets = ${JSON.stringify({ system, profiles, expertSystem, sheetSystem, bundles }, null, 2)}`,
  '',
].join('\n')

const target = join(mod, 'hooks', 'assets.ts')
const current = existsSync(target) ? readFileSync(target, 'utf8') : ''
if (process.argv.includes('--check')) {
  if (current !== body) {
    console.error('hooks/assets.ts is out of date: run node mods/claude-code/scripts/sync-assets.ts')
    process.exit(1)
  }
  console.log('hooks/assets.ts is up to date')
} else {
  writeFileSync(target, body)
  console.log(`wrote ${target} (system + ${Object.keys(profiles).length} profiles: ${Object.keys(profiles).join(', ')})`)
}
