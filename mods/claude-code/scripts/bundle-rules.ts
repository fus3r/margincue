// Metadata that the current card Markdown cannot express. Phrases use exact
// word boundaries. Keep broad topical terms behind a second piece of evidence.
import type { Locale, Pattern, Rules } from '../core/bundle'

type CardRules = {
  label: Locale<string>
  touch: Locale<Rules>
  optionIds?: string[]
  cost?: number
  fr?: { plain: string; expert: string }
  requires?: string[]
  optionFacts?: Record<string, string>
}

const withTerms = (phrase: string, ...groups: string[][]): Pattern => ({ phrase, with: groups })
const r = (match: Pattern[], settled?: string[], exclude?: string[]): Rules =>
  ({ match, ...(settled && { settled }), ...(exclude && { exclude }) })
const card = (en: string, fr: string, english: Rules, french: Rules): CardRules =>
  ({ label: { en, fr }, touch: { en: english, fr: french } })
const guard = (
  en: string, fr: string, cost: number, optionIds: string[], english: Rules, french: Rules,
): CardRules => ({ ...card(en, fr, english, french), cost, optionIds })
const pilot = (
  en: string, fr: string, english: Rules, french: Rules, plain: string, expert: string,
): CardRules => ({ ...card(en, fr, english, french), fr: { plain, expert } })

